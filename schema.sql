-- Social-fatigue tracker: users log their daily social interactions and
-- rate how drained they feel, to spot what wears them out.
-- Re-runnable: every statement uses IF NOT EXISTS / OR REPLACE.

-- PLACEHOLDER: real accounts will need email/auth columns.
-- For now the sample data's Name column maps onto users.name.
CREATE TABLE IF NOT EXISTS users (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL,
    age         SMALLINT CHECK (age BETWEEN 0 AND 130),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Kinds of interaction (Friend, Lecture, Work Meeting, ...).
-- Names are stored in title case so "group work" and "Group Work" match.
CREATE TABLE IF NOT EXISTS interaction_types (
    id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  TEXT NOT NULL UNIQUE
);

-- One logged social interaction.
-- The sample data only records the day, so this is a DATE, not a TIMESTAMPTZ.
CREATE TABLE IF NOT EXISTS interactions (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    interaction_date  DATE NOT NULL,
    type_id           INTEGER NOT NULL REFERENCES interaction_types (id),
    duration_min      INTEGER NOT NULL CHECK (duration_min > 0)
);

CREATE INDEX IF NOT EXISTS interactions_user_date_idx
    ON interactions (user_id, interaction_date);

-- One fatigue rating per user per day.
-- Interaction count and total minutes are not stored here; see daily_summary.
CREATE TABLE IF NOT EXISTS daily_fatigue (
    user_id        INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    log_date       DATE NOT NULL,
    fatigue_score  SMALLINT NOT NULL CHECK (fatigue_score BETWEEN 1 AND 10),
    PRIMARY KEY (user_id, log_date)
);

-- PLACEHOLDER: daily nudge to log interactions and rate fatigue.
CREATE TABLE IF NOT EXISTS reminders (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    remind_at   TIME NOT NULL,
    timezone    TEXT NOT NULL DEFAULT 'America/New_York',
    enabled     BOOLEAN NOT NULL DEFAULT true,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Each day's fatigue score next to the interactions behind it.
CREATE OR REPLACE VIEW daily_summary AS
SELECT
    f.user_id,
    f.log_date,
    f.fatigue_score,
    COUNT(i.id) AS interaction_count,
    COALESCE(SUM(i.duration_min), 0) AS total_duration_min
FROM daily_fatigue f
LEFT JOIN interactions i
    ON i.user_id = f.user_id
   AND i.interaction_date = f.log_date
GROUP BY f.user_id, f.log_date, f.fatigue_score;
